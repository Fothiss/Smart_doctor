import { describe, expect, it } from 'vitest'

import { normalizeLists } from './markdown'

describe('normalizeLists', () => {
  it('разводит перечисление, склеенное моделью в одну строку', () => {
    const answer =
      'Общие принципы: - Пациентам с АГ 2-й степени рекомендуется комбинация 8. - Базовые схемы включают иРААС [3, 5]. - При ХБП можно все группы АГП.'

    expect(normalizeLists(answer)).toBe(
      [
        'Общие принципы:',
        '- Пациентам с АГ 2-й степени рекомендуется комбинация 8.',
        '- Базовые схемы включают иРААС [3, 5].',
        '- При ХБП можно все группы АГП.',
      ].join('\n'),
    )
  })

  it('понимает другие маркеры списка', () => {
    expect(normalizeLists('Список: • первый • второй')).toContain('• первый\n• второй')
    expect(normalizeLists('Список: – первый – второй')).toContain('– первый\n– второй')
  })

  it('разводит нумерованный список', () => {
    expect(normalizeLists('Шаги: 1. измерить 2. записать')).toBe('Шаги:\n1. измерить\n2. записать')
  })

  it('не трогает дефисы внутри слов и диапазонов', () => {
    const answer = 'АГ 2-й степени, доза 5-10 мг, иРААС/АК — всё это не список'

    expect(normalizeLists(answer)).toBe(answer)
  })

  it('одиночный дефис перед строчной буквой остаётся текстом', () => {
    const answer = 'Лечение - это процесс, а не список'

    expect(normalizeLists(answer)).toBe(answer)
  })

  it('одиночный дефис перед заглавной буквы становится пунктом', () => {
    expect(normalizeLists('Итог: - Начинаем с комбинации')).toBe('Итог:\n- Начинаем с комбинации')
  })

  it('не ломает уже размеченный список', () => {
    const answer = 'Введение.\n\n- первый\n- второй'

    expect(normalizeLists(answer)).toBe('Введение.\n\n- первый\n- второй')
  })

  it('две цифры с точкой внутри предложения не всегда список', () => {
    const answer = 'Доза 5. 5 мг принимать утром'

    expect(normalizeLists(answer)).toBe(answer)
  })
})
