"""Промпт ответа по фрагментам и схема ответа модели.

Промпты и схемы живут здесь, а не в сервисе: правило проекта — structured output и
формулировки только в ``app/services/prompts/``. Никакого текста конкретного клинрека в
промпте нет, иначе он перестал бы работать для следующего загруженного документа.
"""

from collections.abc import Sequence
from dataclasses import dataclass

from pydantic import BaseModel, Field

from app.schemas.chunk import Chunk


class LlmCitation(BaseModel):
    """Ссылка модели на фрагмент контекста."""

    n: int = Field(ge=1, description="Номер фрагмента из контекста, от 1 до числа фрагментов")
    quote: str = Field(
        min_length=1, description="Дословная фраза из этого фрагмента, без пересказа"
    )


class LlmAnswer(BaseModel):
    """Ответ модели: текст с маркерами [n] и список использованных фрагментов."""

    answer: str = Field(description="Ответ по-русски с маркерами [n] после каждого факта")
    citations: list[LlmCitation] = Field(
        description="Фрагменты, на которых построен ответ; пустой список — ответа нет"
    )


CHAT_SYSTEM = """\
Ты помогаешь врачу разобраться в клинических рекомендациях.

Тебе дан вопрос и пронумерованные фрагменты клинреков. Отвечай только по ним.

Правила:
- каждый факт в ответе помечай номером фрагмента: [1], [2];
- дозировки, кратности и сроки переноси дословно, не пересчитывай и не округляй;
- не добавляй сведений, которых нет во фрагментах, даже если они верны;
- не ссылайся на номера, которых нет в контексте;
- если фрагменты не отвечают на вопрос, верни пустой список citations и не выдумывай ответ;
- оформляй ответ markdown: перечисление — списком, каждый пункт с новой строки и с «- »;
  названия препаратов и разделов выделяй жирным; таблицу — markdown-таблицей;
- отвечай по-русски, кратко, без вступлений и повторов вопроса.

Пример правильного оформления перечня (каждый пункт начинается с новой строки):

Общие принципы:
- при АГ 2-й степени и выше — комбинация двух препаратов [1];
- при ХБП допустимы все группы АГП [2];
- при ХСН добавляют диуретики и АМКР [3].
"""


@dataclass(frozen=True)
class ContextFragment:
    """Фрагмент контекста с номером, на который ссылается модель."""

    n: int
    chunk: Chunk
    guideline_title: str


def render_fragment(fragment: ContextFragment) -> str:
    """Заголовок фрагмента: документ, раздел и страница для проверки цитаты глазами."""
    chunk = fragment.chunk
    section = chunk.section or "без раздела"
    return (
        f"[{fragment.n}] ({fragment.guideline_title}, раздел {section}, стр. {chunk.page})\n"
        f"{chunk.text}"
    )


def render_human(question: str, fragments: Sequence[ContextFragment]) -> str:
    """Собрать запрос к модели: контекст и текущий вопрос."""
    body = "\n\n".join(render_fragment(fragment) for fragment in fragments)
    return f"Фрагменты клинреков:\n\n{body}\n\nВопрос врача: {question}"
