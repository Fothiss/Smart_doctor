"""Промпт переписывания вопроса врача в поисковый тезис.

Модель не ищет и не отвечает: её работа — убрать эллипсис («а если ещё диабет?») и
привести вопрос к регистру, под который настроена инструкция эмбеддера. Поэтому запрос
формулируется как утверждение клинрека, а не как вопрос и не как набор ключевых слов.
"""

from collections.abc import Sequence
from typing import Protocol

from pydantic import BaseModel, Field


class DialogueMessage(Protocol):
    """Сообщение ленты, нужное переписыванию: роль и текст."""

    role: str

    text: str


class SearchQuery(BaseModel):
    """Запрос для векторного поиска: тезис в регистре клинрека."""

    expression: str = Field(
        description=(
            "Самодостаточный тезис 5-20 слов: предмет и все условия (возраст, "
            "сопутствующие заболевания, степень, препарат). Без местоимений «это», "
            "«там», «его», без слов «поиск», «вопрос», «найди»"
        )
    )
    constraints: list[str] = Field(
        default_factory=list,
        description="Условия вопроса и истории, которые обязаны попасть в тезис, дословно",
    )
    is_followup: bool = Field(
        description="Реплика уточняет предыдущий вопрос, а не начинает новую тему"
    )


REWRITE_SYSTEM = """\
Ты готовишь поисковый запрос по клиническим рекомендациям.

На вход приходят: последние сообщения диалога врача и его новый вопрос. Верни тезис,
по которому будет искаться фрагмент клинрека.

Правила:
- тезис — утверждение в регистре клинических рекомендаций, 5-20 слов, по-русски;
- сохрани все условия из вопроса и истории: возраст, сопутствующие заболевания, степень,
  препарат, срок. Ни одно условие не выбрасывай;
- не добавляй условий, которых не было в вопросе или истории, даже если они кажутся
  вероятными;
- не пересказывай служебные части документа: без слов «поиск», «вопрос», «согласно
  фрагменту»;
- в поле constraints перечисли дословно те условия, которые обязан сохранить тезис;
- is_followup — true, если вопрос уточняет предыдущую реплику, и false, если начинает
  новую тему.
"""

EMPTY_HISTORY_NOTE = "Истории нет: это первый вопрос."
"""Подпись для случая без предыдущих сообщений."""


def render_history(window: Sequence[DialogueMessage]) -> str:
    """Собрать окно истории в виде строк «роль: текст»."""
    if not window:
        return EMPTY_HISTORY_NOTE
    lines = []
    for message in window:
        speaker = "Врач" if message.role == "user" else "Ассистент"
        lines.append(f"{speaker}: {message.text}")
    return "\n".join(lines)


def render_human(question: str, window: Sequence[DialogueMessage]) -> str:
    """Собрать запрос к модели переписывания."""
    return (
        f"Диалог:\n{render_history(window)}\n\n"
        f"Новый вопрос врача: {question}\n\n"
        "Верни тезис для поиска по клинреку."
    )
